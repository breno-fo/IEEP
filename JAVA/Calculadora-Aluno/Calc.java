public class Calc{
    // SOMAÇÃO
    public static int sum(int a, int b){
        return a + b;
    }    

    // SUBTRAÇÃO
    public static int sub(int a, int b){
        return a - b;
    }

    // MULTIPLICAÇÃO
    public static int mult(int a, int b){
        return a * b;
    }

    // DIVISÃO
    public static int div(int a, int b){
        return a / b;
    }
}
